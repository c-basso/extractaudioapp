const PROJECT_ROOT = path.join(__dirname, '..');

/** Markdown for repo root; single source of truth for URLs is `build/constants.js`. */
function buildReadmeMarkdown() {
    const landing = URLS.map(
        (e) => `- [${e.link_label}](${e.url})${e.lang === DEFAULT_LANGUAGE ? ' — default locale' : ''}`
    ).join('\n');
    const extra =
        ADDITIONAL_URLS.length > 0
            ? ADDITIONAL_URLS.map((u) => {
                  const pathPart = u.replace(/^https?:\/\/[^/]+/i, '').replace(/^\//, '') || u;
                  const label = pathPart || u;
                  return `- [${label}](${u})`;
              }).join('\n')
            : '_None._';
    return `# Extract Audio App — published URLs

> **Generated.** Do not edit this file by hand. It is produced by \`npm run build\` from \`build/build.js\` and \`build/constants.js\`.

## Landing pages

${landing}

## Other site URLs

${extra}

## Crawling / discovery

- [sitemap.xml](${SITE_URL}sitemap.xml) — regenerate with \`npm run sitemap\`
- [robots.txt](${SITE_URL}robots.txt) — regenerate with \`npm run sitemap\`

## App Store

- [App Store product page](${APP_STORE_APP_URL})

## Legal and support

- [Privacy policy](${SITE_PRIVACY_URL})
- [Terms of service](${SITE_TERMS_URL})
- [Contact support](${SUPPORT_MAILTO_URL})
`;
}

/** Shared app / legal / store URLs and build-time app metadata (single source: constants.js). */
function injectAppDefaults(data, lang) {
    const currency =
        PRICE_CURRENCY_BY_LANG[lang] ?? PRICE_CURRENCY_BY_LANG[DEFAULT_LANGUAGE];

    data.hero = data.hero || {};
    data.hero.cta_url = APP_STORE_APP_URL;

    data.footer = data.footer || {};
    data.footer.cta_url = APP_STORE_APP_URL;
    data.footer.privacy_url = SITE_PRIVACY_URL;
    data.footer.terms_url = SITE_TERMS_URL;
    data.footer.support_url = SUPPORT_MAILTO_URL;

    data.floating_cta = data.floating_cta || {};
    data.floating_cta.url = APP_STORE_APP_URL;

    data.app_info = data.app_info || {};
    data.app_info.publisher = APP_PUBLISHER;
    data.app_info.version = APP_VERSION;
    data.app_info.file_size = APP_FILE_SIZE;
    data.app_info.price_currency = currency;

    data.app_info.min_ios = APP_MIN_IOS;
    data.app_info.rating_us_value = APP_RATING_US_VALUE;
    data.app_info.rating_us_count = APP_RATING_US_COUNT;
    data.app_info.store_url = APP_STORE_APP_URL;

    data.schema_rating = {
        rating_value: SCHEMA_AGGREGATE_RATING_VALUE,
        rating_count: SCHEMA_AGGREGATE_RATING_COUNT,
        best_rating: SCHEMA_AGGREGATE_BEST_RATING,
        worst_rating: SCHEMA_AGGREGATE_WORST_RATING
    };
}

function resolveSiteImageUrlToLocalPath(imageUrl) {
    if (imageUrl.startsWith(SITE_URL)) {
        const relativePath = imageUrl.replace(SITE_URL, '');
        return path.join(PROJECT_ROOT, relativePath);
    }
    return path.join(PROJECT_ROOT, imageUrl);
}

